package com.vyrriox.rspolymorph.selftest;

import com.vyrriox.rspolymorph.RsPolymorph;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.event.TickEvent;
import net.minecraftforge.eventbus.api.SubscribeEvent;
import net.minecraftforge.fml.common.Mod;

/**
 * Pumps the selftest from the end of the client tick. Newer targets do it with a mixin; this Forge has none.
 *
 * Author: vyrriox
 */
@Mod.EventBusSubscriber(modid = RsPolymorph.MOD_ID, value = Dist.CLIENT)
public final class SelftestDriver {

    private SelftestDriver() {
    }

    @SubscribeEvent
    public static void onClientTick(TickEvent.ClientTickEvent event) {
        if (event.phase == TickEvent.Phase.END) {
            Selftest.onClientTick();
        }
    }
}
